#!/usr/bin/env python3
"""Run with the isolated Checkov interpreter to verify the crypto replacement."""
import hashlib
import importlib.util
from pathlib import Path
import tempfile
import unittest


class DependencyTests(unittest.TestCase):
    def test_vulnerable_private_key_implementation_is_absent(self):
        self.assertIsNone(importlib.util.find_spec("ecdsa"))


class SignatureTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        from cryptography.hazmat.primitives import hashes, serialization
        from cryptography.hazmat.primitives.asymmetric import ec
        from checkov.common.external_checks.verification.errors import SignatureVerificationError
        from checkov.common.external_checks.verification.keys import load_public_keys
        from checkov.common.external_checks.verification.verifier import VerificationResult, verify_bytes, verify_file
        cls.hashes, cls.serialization, cls.ec = hashes, serialization, ec
        cls.key_error, cls.result = SignatureVerificationError, VerificationResult
        cls.load_keys, cls.verify, cls.verify_file = staticmethod(load_public_keys), staticmethod(verify_bytes), staticmethod(verify_file)

    def setUp(self):
        self.directory = tempfile.TemporaryDirectory()
        self.addCleanup(self.directory.cleanup)
        self.private = self.ec.generate_private_key(self.ec.SECP256R1())
        self.pem = self.private.public_key().public_bytes(self.serialization.Encoding.PEM, self.serialization.PublicFormat.SubjectPublicKeyInfo)
        self.key_path = Path(self.directory.name) / "key.pem"
        self.key_path.write_bytes(self.pem)
        self.keys = self.load_keys([str(self.key_path)])
        self.payload = b'check = "trusted synthetic fixture"\n'
        self.signature = self.private.sign(self.payload, self.ec.ECDSA(self.hashes.SHA256()))

    def signed(self, signature=None, payload=None):
        return (self.payload if payload is None else payload) + b"# checkov-digest: " + (self.signature if signature is None else signature).hex().encode() + b"\n"

    def test_valid_signature_returns_exact_original_bytes(self):
        self.assertEqual(self.verify(self.signed(), self.keys), (self.result.OK, self.payload))

    def test_existing_ecdsa_signed_fixture_is_compatible(self):
        # Synthetic P-256 private scalar 1; fixture generated by the previous library.
        self.key_path.write_bytes(b"-----BEGIN PUBLIC KEY-----\nMFkwEwYHKoZIzj0CAQYIKoZIzj0DAQcDQgAEaxfR8uEsQkf4vOblY6RA8ncDfYEt6zOg9KE5RdiY\nwpZP40Li/hp/m47n60p8D54WK84zV2sxXs7LtkBoN79R9Q==\n-----END PUBLIC KEY-----\n")
        keys = self.load_keys([str(self.key_path)])
        signature = bytes.fromhex("304602210085b496ff9bcd335f67ac6a12913ee0318a678b530cd56c8d9e04b64cb9e99882022100ab79d323bef852a01d56845143f2369ed94d7cd447a232e45f5feeada043d7ab")
        self.assertEqual(keys[0].fingerprint_hex, "5cd252fb0ce8932436faf8ccd1040981b89ee4ad6b9fe9e2a2b7e71aacb27cd3")
        self.assertEqual(self.verify(self.signed(signature), keys), (self.result.OK, self.payload))

    def test_fingerprint_remains_sha256_of_spki_der(self):
        der = self.private.public_key().public_bytes(self.serialization.Encoding.DER, self.serialization.PublicFormat.SubjectPublicKeyInfo)
        self.assertEqual(self.keys[0].fingerprint_hex, hashlib.sha256(der).hexdigest())

    def test_tampered_payload_returns_no_executable_bytes(self):
        self.assertEqual(self.verify(self.signed(payload=b"tampered\n"), self.keys), (self.result.UNKNOWN_KEY, b""))

    def test_other_signing_key_returns_no_executable_bytes(self):
        other = self.ec.generate_private_key(self.ec.SECP256R1())
        signature = other.sign(self.payload, self.ec.ECDSA(self.hashes.SHA256()))
        self.assertEqual(self.verify(self.signed(signature), self.keys), (self.result.UNKNOWN_KEY, b""))

    def test_noncanonical_or_out_of_range_der_is_rejected(self):
        from cryptography.hazmat.primitives.asymmetric.utils import encode_dss_signature
        # These encodings fit the trailer length bound, so DER/range checks must reject them.
        for signature in (encode_dss_signature(2**254, 2**254) + b"\0", encode_dss_signature(2**256, 2**255), encode_dss_signature(2**255, 2**256)):
            with self.subTest(signature=signature.hex()):
                self.assertEqual(self.verify(self.signed(signature), self.keys), (self.result.BAD_SIGNATURE, b""))

    def test_missing_and_duplicate_trailers_fail_closed(self):
        self.assertEqual(self.verify(self.payload, self.keys), (self.result.NO_SIGNATURE, b""))
        self.assertEqual(self.verify(self.signed() + self.signed().splitlines(keepends=True)[-1], self.keys), (self.result.DOUBLE_TRAILER, b""))

    def test_malformed_and_non_p256_keys_are_rejected(self):
        from cryptography.hazmat.primitives.asymmetric import rsa
        unsupported = (b"not a key", self.ec.generate_private_key(self.ec.SECP384R1()).public_key().public_bytes(self.serialization.Encoding.PEM, self.serialization.PublicFormat.SubjectPublicKeyInfo), rsa.generate_private_key(public_exponent=65537, key_size=2048).public_key().public_bytes(self.serialization.Encoding.PEM, self.serialization.PublicFormat.SubjectPublicKeyInfo))
        for pem in unsupported:
            with self.subTest(pem=pem[:30]):
                self.key_path.write_bytes(pem)
                with self.assertRaises(self.key_error):
                    self.load_keys([str(self.key_path)])

    def test_unreadable_key_and_file_do_not_bypass_verification(self):
        missing = str(Path(self.directory.name) / "missing")
        with self.assertRaises(self.key_error):
            self.load_keys([missing])
        self.assertEqual(self.verify_file(missing, self.keys), (self.result.IO_ERROR, b""))

    def test_empty_trust_store_is_rejected(self):
        with self.assertRaises(ValueError):
            self.verify(self.signed(), [])


if __name__ == "__main__":
    unittest.main()
